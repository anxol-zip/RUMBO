-- ───────────── Reglas que hace cumplir la base ─────────────

-- RN_05: un reporte que cuenta por sesión y punto cada 30 min. reportes.filtrar lo revisa antes para
-- dar un mensaje claro y guardar el repetido como 'descartado'; esto es lo que no se puede saltar.
-- El candado por sesión y punto evita que dos reportes simultáneos pasen la revisión a la vez.
CREATE OR REPLACE FUNCTION reporte_uno_cada_30_min() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF new.estado <> 'descartado' THEN
        PERFORM pg_advisory_xact_lock(hashtext(new.sesion_id || ':' || new.punto_id));
        IF EXISTS (
            SELECT 1 FROM reporte r
            WHERE r.sesion_id = new.sesion_id
              AND r.punto_id = new.punto_id
              AND r.estado <> 'descartado'
              AND new.creado_en::timestamp - r.creado_en::timestamp < interval '30 minutes'
        ) THEN
            RAISE EXCEPTION 'RN_05: reporte repetido';
        END IF;
    END IF;
    RETURN new;
END;
$$;

CREATE OR REPLACE TRIGGER reporte_uno_cada_30_min
BEFORE INSERT ON reporte
FOR EACH ROW EXECUTE FUNCTION reporte_uno_cada_30_min();

-- ───────────── Nadie entra por fuera del backend ─────────────

-- RLS sin políticas: la clave pública de Supabase (roles anon y authenticated) no ve ni escribe nada.
-- El backend entra como postgres (dueño de las tablas), que no pasa por RLS.
DO $$
DECLARE t text;
BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = current_schema() LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    END LOOP;
END;
$$;

-- ───────────── Cuentas de turista (feature 002) ─────────────
-- Login con Microsoft vía Supabase Auth (auth.users). El frontend lee y escribe estas tablas directo
-- con supabase-js; las reglas viven aquí (RLS, CHECK, UNIQUE y triggers), así nadie se las salta.
-- Las funciones guardan el esquema donde se crearon (SET search_path FROM CURRENT): public en los
-- ambientes y prueba_<hex> en las pruebas. Todo es idempotente: corre en cada arranque.

DO $$ BEGIN
    EXECUTE format('GRANT USAGE ON SCHEMA %I TO anon, authenticated', current_schema());
END $$;

-- Perfil: uno por usuario de Supabase. El rol solo lo cambia el equipo (SQL Editor).
CREATE TABLE IF NOT EXISTS perfil (
    id          uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    nombre      TEXT COLLATE "C" NOT NULL,
    rol         TEXT COLLATE "C" NOT NULL DEFAULT 'turista' CHECK (rol IN ('turista', 'administrador')),
    gustos      TEXT[] NOT NULL DEFAULT '{}',
    creado_en   timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION es_admin() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path FROM CURRENT AS $$
    SELECT EXISTS (SELECT 1 FROM perfil WHERE id = auth.uid() AND rol = 'administrador');
$$;

-- Al registrarse alguien se crea su perfil de turista. Si esto fallara, nadie podría entrar:
-- por eso todo lleva coalesce y ON CONFLICT. También corre en cada inicio de sesión (Supabase
-- actualiza los metadatos): si el perfil quedó como 'Turista' y ahora llega el nombre, lo toma.
CREATE OR REPLACE FUNCTION crear_perfil() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT AS $$
BEGIN
    INSERT INTO perfil (id, nombre)
    VALUES (new.id, coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
                             nullif(trim(new.raw_user_meta_data ->> 'name'), ''), 'Turista'))
    ON CONFLICT (id) DO UPDATE SET nombre = excluded.nombre
        WHERE perfil.nombre = 'Turista' AND excluded.nombre <> 'Turista';
    RETURN new;
END;
$$;

-- Un trigger por esquema (crear_perfil_public, crear_perfil_prueba_x…): el de cada prueba se va con
-- su DROP SCHEMA … CASCADE porque depende de la función de ese esquema.
DO $$ BEGIN
    EXECUTE format('CREATE OR REPLACE TRIGGER %I AFTER INSERT OR UPDATE OF raw_user_meta_data ON auth.users '
                   'FOR EACH ROW EXECUTE FUNCTION %I.crear_perfil()',
                   'crear_perfil_' || current_schema(), current_schema());
END $$;

-- Usuarios que entraron antes de existir el trigger: se les crea su perfil (solo en los ambientes).
DO $$ BEGIN
    IF current_schema() = 'public' THEN
        INSERT INTO perfil (id, nombre)
        SELECT u.id, coalesce(nullif(trim(u.raw_user_meta_data ->> 'full_name'), ''),
                              nullif(trim(u.raw_user_meta_data ->> 'name'), ''), 'Turista')
        FROM auth.users u
        ON CONFLICT (id) DO NOTHING;
    END IF;
END $$;

-- Borrar mi cuenta: borra el usuario de Supabase y, en cascada, todo lo suyo.
CREATE OR REPLACE FUNCTION borrar_mi_cuenta() RETURNS void
LANGUAGE sql SECURITY DEFINER SET search_path FROM CURRENT AS $$
    DELETE FROM auth.users WHERE id = auth.uid();
$$;

CREATE TABLE IF NOT EXISTS favorito (
    usuario_id  uuid NOT NULL DEFAULT auth.uid() REFERENCES perfil(id) ON DELETE CASCADE,
    punto_id    BIGINT NOT NULL REFERENCES punto(id),
    creado_en   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (usuario_id, punto_id)
);

CREATE TABLE IF NOT EXISTS resena (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  uuid NOT NULL DEFAULT auth.uid() REFERENCES perfil(id) ON DELETE CASCADE,
    punto_id    BIGINT NOT NULL REFERENCES punto(id),
    autor       TEXT COLLATE "C" NOT NULL,              -- "Axel G.", lo pone antes_de_resena
    estrellas   SMALLINT NOT NULL CHECK (estrellas BETWEEN 1 AND 5),
    accesible   BOOLEAN,                                -- NULL = "no sé"
    texto       TEXT COLLATE "C" CHECK (char_length(texto) <= 1000),
    estado      TEXT COLLATE "C" NOT NULL DEFAULT 'visible' CHECK (estado IN ('visible', 'oculta')),
    utiles      INTEGER NOT NULL DEFAULT 0,             -- lo lleva contar_util
    creada_en   timestamptz NOT NULL DEFAULT now(),
    editada_en  timestamptz,
    UNIQUE (usuario_id, punto_id)                       -- una reseña por persona y lugar
);
CREATE INDEX IF NOT EXISTS resena_punto_estado ON resena (punto_id, estado);

CREATE TABLE IF NOT EXISTS resena_util (
    usuario_id  uuid NOT NULL DEFAULT auth.uid() REFERENCES perfil(id) ON DELETE CASCADE,
    resena_id   BIGINT NOT NULL REFERENCES resena(id) ON DELETE CASCADE,
    PRIMARY KEY (usuario_id, resena_id)
);

CREATE TABLE IF NOT EXISTS resena_denuncia (
    usuario_id  uuid NOT NULL DEFAULT auth.uid() REFERENCES perfil(id) ON DELETE CASCADE,
    resena_id   BIGINT NOT NULL REFERENCES resena(id) ON DELETE CASCADE,
    motivo      TEXT COLLATE "C" NOT NULL CHECK (char_length(motivo) BETWEEN 1 AND 300),
    creada_en   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (usuario_id, resena_id)
);

-- RN_R1 (máx. 10 reseñas por hora) y nombre público.
CREATE OR REPLACE FUNCTION antes_de_resena() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF (SELECT count(*) FROM resena
        WHERE usuario_id = new.usuario_id AND creada_en > now() - interval '1 hour') >= 10 THEN
        RAISE EXCEPTION 'RN_R1: máximo 10 reseñas por hora';
    END IF;
    SELECT split_part(nombre, ' ', 1)
           || coalesce(' ' || nullif(left(split_part(nombre, ' ', 2), 1), '') || '.', '')
      INTO new.autor FROM perfil WHERE id = new.usuario_id;
    RETURN new;
END;
$$;
CREATE OR REPLACE TRIGGER antes_de_resena BEFORE INSERT ON resena
FOR EACH ROW EXECUTE FUNCTION antes_de_resena();

-- RN_R2: solo el administrador modera (estado) y solo el autor edita el contenido.
-- auth.uid() es NULL cuando escribe el backend o el equipo (postgres): no aplica.
CREATE OR REPLACE FUNCTION al_editar_resena() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF new.estado IS DISTINCT FROM old.estado AND auth.uid() IS NOT NULL AND NOT es_admin() THEN
        RAISE EXCEPTION 'RN_R2: solo un administrador modera reseñas';
    END IF;
    IF (new.estrellas, new.accesible, new.texto) IS DISTINCT FROM (old.estrellas, old.accesible, old.texto) THEN
        IF auth.uid() IS NOT NULL AND auth.uid() <> old.usuario_id THEN
            RAISE EXCEPTION 'RN_R2: solo el autor edita su reseña';
        END IF;
        new.editada_en := now();
    END IF;
    RETURN new;
END;
$$;
CREATE OR REPLACE TRIGGER al_editar_resena BEFORE UPDATE ON resena
FOR EACH ROW EXECUTE FUNCTION al_editar_resena();

-- Contador de "útil" (SECURITY DEFINER: nadie de la app puede escribir utiles directo).
CREATE OR REPLACE FUNCTION contar_util() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT AS $$
BEGIN
    UPDATE resena SET utiles = utiles + (CASE WHEN tg_op = 'INSERT' THEN 1 ELSE -1 END)
    WHERE id = coalesce(new.resena_id, old.resena_id);
    RETURN NULL;
END;
$$;
CREATE OR REPLACE TRIGGER contar_util AFTER INSERT OR DELETE ON resena_util
FOR EACH ROW EXECUTE FUNCTION contar_util();

-- Resumen de un lugar (solo reseñas visibles). Corre con los permisos de quien lo pide.
CREATE OR REPLACE FUNCTION resumen_resenas(p_punto BIGINT)
RETURNS TABLE (promedio numeric, total bigint, e1 bigint, e2 bigint, e3 bigint, e4 bigint, e5 bigint,
               pct_accesible numeric)
LANGUAGE sql STABLE SET search_path FROM CURRENT AS $$
    SELECT round(avg(estrellas), 1), count(*),
           count(*) FILTER (WHERE estrellas = 1), count(*) FILTER (WHERE estrellas = 2),
           count(*) FILTER (WHERE estrellas = 3), count(*) FILTER (WHERE estrellas = 4),
           count(*) FILTER (WHERE estrellas = 5),
           round(100.0 * count(*) FILTER (WHERE accesible)
                 / nullif(count(*) FILTER (WHERE accesible IS NOT NULL), 0))
    FROM resena WHERE punto_id = p_punto AND estado = 'visible';
$$;

-- Permisos: primero nada, luego solo lo necesario (igual en public y en los esquemas de prueba).
REVOKE ALL ON perfil, favorito, resena, resena_util, resena_denuncia FROM anon, authenticated;
GRANT SELECT, UPDATE (gustos) ON perfil TO authenticated;
GRANT SELECT, INSERT (punto_id), DELETE ON favorito TO authenticated;
GRANT SELECT ON resena TO anon, authenticated;
GRANT INSERT (punto_id, estrellas, accesible, texto), DELETE ON resena TO authenticated;
GRANT UPDATE (estrellas, accesible, texto, estado) ON resena TO authenticated;
GRANT SELECT ON resena_util TO anon, authenticated;
GRANT INSERT (resena_id), DELETE ON resena_util TO authenticated;
GRANT SELECT, INSERT (resena_id, motivo) ON resena_denuncia TO authenticated;

REVOKE ALL ON FUNCTION es_admin(), borrar_mi_cuenta(), resumen_resenas(BIGINT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION borrar_mi_cuenta() TO authenticated;
-- anon también: la política "leer reseñas" pregunta es_admin() (sin sesión siempre es false).
GRANT EXECUTE ON FUNCTION es_admin() TO anon, authenticated;
GRANT EXECUTE ON FUNCTION resumen_resenas(BIGINT) TO anon, authenticated;

