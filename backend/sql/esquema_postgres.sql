-- Esquema de RUMBO en PostgreSQL (Supabase). Reemplaza a sql/esquema.sql (SQLite), que queda solo
-- como referencia. Mismas 18 tablas, campos y llaves; las diferencias están en
-- specs/001-base-en-supabase/data-model.md.
--
-- * Idempotente: crear_esquema() lo corre en cada arranque sin tocar los datos.
-- * Sin "public.": se crea en el esquema actual (search_path), así las pruebas usan uno temporal.
-- * Todo TEXT lleva COLLATE "C": compara byte por byte, como SQLite (la base usa en_US.UTF-8).
-- * Fechas siguen como TEXT ISO ('YYYY-MM-DD HH:MM'); solo RN_05 las convierte.

-- ───────────── Catálogos ─────────────

CREATE TABLE IF NOT EXISTS fuente (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          TEXT COLLATE "C" NOT NULL UNIQUE,
    url             TEXT COLLATE "C",
    licencia        TEXT COLLATE "C",
    frecuencia      TEXT COLLATE "C",
    fecha_descarga  TEXT COLLATE "C",
    archivo         TEXT COLLATE "C",
    hash_archivo    TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS destino (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      TEXT COLLATE "C" NOT NULL UNIQUE,   -- como lo nombra el Observatorio, normalizado
    cve_mun     TEXT COLLATE "C",                   -- clave INEGI del municipio (del propio DENUE)
    lat DOUBLE PRECISION, lon DOUBLE PRECISION,
    es_piloto   INTEGER DEFAULT 0,
    es_agregado INTEGER DEFAULT 0                   -- 1 = 'Estado' o 'Resto del Estado' (no es un lugar)
);

CREATE TABLE IF NOT EXISTS punto (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave             TEXT COLLATE "C" NOT NULL UNIQUE,
    nombre            TEXT COLLATE "C" NOT NULL,
    destino_id        BIGINT NOT NULL REFERENCES destino(id),
    municipio         TEXT COLLATE "C",
    tipo              TEXT COLLATE "C",
    categorias        TEXT COLLATE "C",
    interior          INTEGER,
    lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
    horario           TEXT COLLATE "C",
    costo_mxn         DOUBLE PRECISION,
    duracion_sugerida TEXT COLLATE "C",
    ficha             TEXT COLLATE "C",
    es_inah           INTEGER DEFAULT 0,
    clee_denue        TEXT COLLATE "C",
    osm_id            TEXT COLLATE "C",
    fuente_texto      TEXT COLLATE "C",              -- columna 'fuente' del catálogo
    fuente_id         BIGINT REFERENCES fuente(id),
    verificado        INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS recinto_inah (
    clave_siinah  TEXT COLLATE "C" PRIMARY KEY,
    nombre        TEXT COLLATE "C" NOT NULL,
    siglas        TEXT COLLATE "C",
    punto_id      BIGINT REFERENCES punto(id)        -- NULL si no está en la zona piloto
);

CREATE TABLE IF NOT EXISTS evento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      TEXT COLLATE "C" NOT NULL,
    punto_id    BIGINT REFERENCES punto(id),
    destino_id  BIGINT REFERENCES destino(id),
    inicio      TEXT COLLATE "C" NOT NULL, fin TEXT COLLATE "C" NOT NULL,
    impacto     TEXT COLLATE "C" CHECK (impacto IN ('bajo','medio','alto')),
    fuente_url  TEXT COLLATE "C" NOT NULL,
    verificado  INTEGER DEFAULT 0,                   -- 0 = solo prensa: se guarda, pero el modelo no lo usa
    nota        TEXT COLLATE "C"                     -- horario real, sede, discrepancias entre fuentes
);

CREATE TABLE IF NOT EXISTS calendario (
    fecha         TEXT COLLATE "C" PRIMARY KEY,
    dia_semana    INTEGER,                           -- 0 = lunes
    es_festivo    INTEGER, es_puente INTEGER, es_vacaciones INTEGER
);

-- ───────────── Hechos oficiales ─────────────

CREATE TABLE IF NOT EXISTS hecho_observatorio (
    destino_id  BIGINT REFERENCES destino(id),
    periodo     TEXT COLLATE "C",                    -- 'YYYY-MM'
    indicador   TEXT COLLATE "C",
    valor       DOUBLE PRECISION,
    es_pandemia INTEGER DEFAULT 0,
    fuente_id   BIGINT REFERENCES fuente(id),
    PRIMARY KEY (destino_id, periodo, indicador)
);

CREATE TABLE IF NOT EXISTS hecho_inah (
    clave_siinah    TEXT COLLATE "C" REFERENCES recinto_inah(clave_siinah),
    periodo         TEXT COLLATE "C",
    tipo_visitante  TEXT COLLATE "C",
    nacionalidad    TEXT COLLATE "C",                -- 'nacional' / 'extranjero'
    visitas         INTEGER,
    fuente_id       BIGINT REFERENCES fuente(id),
    PRIMARY KEY (clave_siinah, periodo, tipo_visitante, nacionalidad)
);

CREATE TABLE IF NOT EXISTS establecimiento (
    clee        TEXT COLLATE "C" PRIMARY KEY,
    nombre      TEXT COLLATE "C" NOT NULL,
    codigo_act  TEXT COLLATE "C" NOT NULL,
    nombre_act  TEXT COLLATE "C",
    giro        TEXT COLLATE "C",                    -- 'museo_sitio', 'hospedaje', 'alimentos'
    per_ocu     TEXT COLLATE "C",
    cve_mun     TEXT COLLATE "C",
    municipio   TEXT COLLATE "C",
    lat DOUBLE PRECISION, lon DOUBLE PRECISION,
    fuente_id   BIGINT REFERENCES fuente(id)
);

CREATE TABLE IF NOT EXISTS matriz_traslado (
    origen_id    BIGINT REFERENCES punto(id),
    destino_id   BIGINT REFERENCES punto(id),
    minutos_base DOUBLE PRECISION, km DOUBLE PRECISION,       -- en coche, sin tráfico
    minutos_pie  DOUBLE PRECISION, km_pie DOUBLE PRECISION,   -- a pie
    fuente_id    BIGINT REFERENCES fuente(id),
    PRIMARY KEY (origen_id, destino_id)
);

-- ───────────── En vivo ─────────────

CREATE TABLE IF NOT EXISTS obs_clima (
    punto_id      BIGINT REFERENCES punto(id),
    consultado_en TEXT COLLATE "C",
    valido_para   TEXT COLLATE "C",
    temp_c DOUBLE PRECISION, prob_lluvia_pct DOUBLE PRECISION, lluvia_mm DOUBLE PRECISION,
    weather_code INTEGER,
    PRIMARY KEY (punto_id, consultado_en, valido_para)
);

CREATE TABLE IF NOT EXISTS obs_trafico (
    tramo             TEXT COLLATE "C",
    consultado_en     TEXT COLLATE "C",
    vel_actual DOUBLE PRECISION, vel_libre DOUBLE PRECISION,
    factor            DOUBLE PRECISION,
    minutos_actual    DOUBLE PRECISION,              -- TomTom Routing por corredor
    minutos_libre     DOUBLE PRECISION,
    minutos_historico DOUBLE PRECISION,
    km                DOUBLE PRECISION,
    PRIMARY KEY (tramo, consultado_en)
);

-- ───────────── Lo que genera la app ─────────────

CREATE TABLE IF NOT EXISTS sesion (
    id          TEXT COLLATE "C" PRIMARY KEY,
    creada_en   TEXT COLLATE "C",
    perfil      TEXT COLLATE "C",
    es_demo     INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS reporte (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id     TEXT COLLATE "C" REFERENCES sesion(id),
    punto_id      BIGINT REFERENCES punto(id),
    creado_en     TEXT COLLATE "C" NOT NULL,
    nivel         INTEGER CHECK (nivel IN (1,2,3)),
    espera_min    INTEGER,
    distancia_m   DOUBLE PRECISION,
    peso          DOUBLE PRECISION,
    estado        TEXT COLLATE "C" DEFAULT 'valido',
    motivo        TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS busqueda (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id      TEXT COLLATE "C" REFERENCES sesion(id),
    creada_en      TEXT COLLATE "C",
    punto_pedido   BIGINT REFERENCES punto(id),
    punto_sugerido BIGINT REFERENCES punto(id),
    motivo         TEXT COLLATE "C",
    aceptada       INTEGER
);

-- ───────────── Derivados ─────────────

CREATE TABLE IF NOT EXISTS afluencia_estimada (
    punto_id     BIGINT REFERENCES punto(id),
    para_hora    TEXT COLLATE "C",
    base         DOUBLE PRECISION,
    f_dia_hora   DOUBLE PRECISION, f_evento DOUBLE PRECISION, f_clima DOUBLE PRECISION,
    estimacion   DOUBLE PRECISION,
    n_reportes   INTEGER,
    valor_final  DOUBLE PRECISION,
    semaforo     TEXT COLLATE "C",
    confianza    TEXT COLLATE "C",
    PRIMARY KEY (punto_id, para_hora)
);

CREATE TABLE IF NOT EXISTS umbral_punto (
    punto_id     BIGINT PRIMARY KEY REFERENCES punto(id),
    bajo         DOUBLE PRECISION NOT NULL,
    alto         DOUBLE PRECISION NOT NULL,
    metodo       TEXT COLLATE "C" CHECK (metodo IN ('percentil','general','manual')),
    n_muestras   INTEGER,
    calculado_en TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS ajuste_manual (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    punto_id     BIGINT REFERENCES punto(id),
    color        TEXT COLLATE "C" CHECK (color IN ('verde','amarillo','rojo')),
    motivo       TEXT COLLATE "C" NOT NULL,
    creado_en    TEXT COLLATE "C" NOT NULL,
    hasta        TEXT COLLATE "C" NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_reporte_punto_fecha ON reporte (punto_id, creado_en);
CREATE INDEX IF NOT EXISTS ix_establecimiento_mun ON establecimiento (cve_mun, giro);

-- ───────────── Reglas que hace cumplir la base ─────────────

-- RN_05: un reporte que cuenta por sesión y punto cada 30 min. reportes.filtrar lo revisa antes para
-- dar un mensaje claro y guardar el repetido como 'descartado'; esto es lo que no se puede saltar.
-- El candado por sesión y punto evita que dos reportes simultáneos pasen la revisión a la vez.
CREATE OR REPLACE FUNCTION reporte_uno_cada_30_min() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF new.estado <> 'descartado' THEN
        PERFORM pg_advisory_xact_lock(hashtext(new.sesion_id || ':' || new.punto_id));
        IF EXISTS (
            SELECT 1 FROM reporte r
            WHERE r.sesion_id = new.sesion_id
              AND r.punto_id = new.punto_id
              AND r.estado <> 'descartado'
              AND new.creado_en::timestamp - r.creado_en::timestamp < interval '30 minutes'
        ) THEN
            RAISE EXCEPTION 'RN_05: reporte repetido';
        END IF;
    END IF;
    RETURN new;
END;
$$;

CREATE OR REPLACE TRIGGER reporte_uno_cada_30_min
BEFORE INSERT ON reporte
FOR EACH ROW EXECUTE FUNCTION reporte_uno_cada_30_min();

-- ───────────── Nadie entra por fuera del backend ─────────────

-- RLS sin políticas: la clave pública de Supabase (roles anon y authenticated) no ve ni escribe nada.
-- El backend entra como postgres (dueño de las tablas), que no pasa por RLS.
DO $$
DECLARE t text;
BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = current_schema() LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    END LOOP;
END;
$$;
